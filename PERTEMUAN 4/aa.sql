CREATE TABLE IF NOT EXISTS admin (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	username VARCHAR(100) NOT NULL UNIQUE,
	password VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS "buku" (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	judul VARCHAR(255) NOT NULL,
	penulis VARCHAR(150) NOT NULL,
	penerbit VARCHAR(150) NOT NULL,
	tahun_terbit SMALLINT NOT NULL
		CHECK (tahun_terbit BETWEEN 1901 AND 2155),
	stok INTEGER NOT NULL
		CHECK (stok >= 0)
);
CREATE TABLE IF NOT EXISTS "user" (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	nama_lengkap VARCHAR(150) NOT NULL,
	username VARCHAR(100) NOT NULL UNIQUE,
	email VARCHAR(150) NOT NULL UNIQUE,
	password VARCHAR(255) NOT NULL,
	created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Tabel pendukung menu Peminjaman Buku (mencatat siapa meminjam buku apa).
CREATE TABLE IF NOT EXISTS peminjaman (
	id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
	user_id INTEGER NOT NULL REFERENCES "user"(id) ON DELETE CASCADE,
	buku_id INTEGER NOT NULL REFERENCES buku(id) ON DELETE RESTRICT,
	tanggal_pinjam DATE NOT NULL DEFAULT CURRENT_DATE,
	jatuh_tempo DATE NOT NULL DEFAULT (CURRENT_DATE + 7),
	tanggal_kembali DATE,
	status VARCHAR(20) NOT NULL DEFAULT 'dipinjam'
		CHECK (status IN ('dipinjam', 'dikembalikan'))
);

-- Satu pengguna tidak boleh meminjam buku yang sama dua kali selama belum dikembalikan.
CREATE UNIQUE INDEX IF NOT EXISTS uq_peminjaman_aktif
	ON peminjaman (user_id, buku_id) WHERE status = 'dipinjam';

